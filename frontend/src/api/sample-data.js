export function getRegistrations({
  search = "",
  type = "",
  status = "",
  page = 1,
  pageSize = 10,
} = {}) {
  const normalizedSearch = search.trim().toLowerCase();

  const filtered = SAMPLE_REGISTRATIONS.filter((reg) => {
    const matchesSearch = normalizedSearch
      ? reg.participantName.toLowerCase().includes(normalizedSearch) ||
        reg.registrationNumber.toLowerCase().includes(normalizedSearch) ||
        reg.carMakeModel.toLowerCase().includes(normalizedSearch) ||
        reg.plateNumber.toLowerCase().includes(normalizedSearch)
      : true;

    const matchesType = type ? reg.registrationType === type : true;
    const matchesStatus = status ? reg.status === status : true;

    return matchesSearch && matchesType && matchesStatus;
  });

  const totalCount = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalCount / pageSize));
  const safePage = Math.min(Math.max(1, page), totalPages);
  const startIndex = (safePage - 1) * pageSize;
  const items = filtered.slice(startIndex, startIndex + pageSize);

  return {
    items,
    page: safePage,
    pageSize,
    totalCount,
    totalPages,
  };
}

export function getSummary() {
  const totalRegistrations = SAMPLE_REGISTRATIONS.length;
  const confirmed = SAMPLE_REGISTRATIONS.filter(
    (r) => r.status === "Confirmed",
  ).length;
  const checkedIn = SAMPLE_REGISTRATIONS.filter(
    (r) => r.status === "Checked In",
  ).length;
  const pending = SAMPLE_REGISTRATIONS.filter(
    (r) => r.status === "Pending",
  ).length;
  const cancelled = SAMPLE_REGISTRATIONS.filter(
    (r) => r.status === "Cancelled",
  ).length;

  const totalFees = SAMPLE_REGISTRATIONS.reduce(
    (sum, r) => sum + Number(r.registrationFee || 0),
    0,
  );
  const totalPayments = SAMPLE_REGISTRATIONS.reduce(
    (sum, r) => sum + Number(r.amountPaid || 0),
    0,
  );
  const uncollectedPayments = totalFees - totalPayments;

  return {
    totalRegistrations,
    confirmed,
    checkedIn,
    pending,
    cancelled,
    totalFees,
    totalPayments,
    uncollectedPayments,
  };
}
